package io.github.axolotlclient.mixin;

import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.player.PlayerCapeModel;
import net.minecraft.client.renderer.entity.state.AvatarRenderState;
import org.spongepowered.asm.mixin.Final;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.Shadow;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;

/** ghost client: las capas de ghost client son más finas que las normales (un tercio de grosor). */
@Mixin(PlayerCapeModel.class)
public abstract class GhostThinCapeMixin {
	@Shadow
	@Final
	private ModelPart cape;

	@Inject(method = "setupAnim(Lnet/minecraft/client/renderer/entity/state/AvatarRenderState;)V", at = @At("TAIL"))
	private void ghost$thin(AvatarRenderState state, CallbackInfo ci) {
		var tex = state.skin == null ? null : state.skin.cape();
		boolean ghost = tex != null && tex.texturePath().getPath().startsWith("textures/ghost/cosmetics/");
		cape.zScale = ghost ? 0.35f : 1f;
	}
}

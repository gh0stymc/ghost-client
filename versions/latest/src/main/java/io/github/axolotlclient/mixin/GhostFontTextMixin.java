package io.github.axolotlclient.mixin;

import io.github.axolotlclient.ghost.GhostFont;
import net.minecraft.client.gui.GuiGraphicsExtractor;
import net.minecraft.util.FormattedCharSequence;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.ModifyVariable;

/** ghost client: el texto que se dibuja en una pantalla de ghost client lleva la letra Inter. */
@Mixin(GuiGraphicsExtractor.class)
public abstract class GhostFontTextMixin {

	@ModifyVariable(method = "text(Lnet/minecraft/client/gui/Font;Lnet/minecraft/util/FormattedCharSequence;IIIZ)V", at = @At("HEAD"), argsOnly = true)
	private FormattedCharSequence ghost$font(FormattedCharSequence text) {
		return GhostFont.active() ? GhostFont.wrap(text) : text;
	}
}
